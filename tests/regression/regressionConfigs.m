function cfgs = regressionConfigs()
% REGRESSIONCONFIGS  The configurations pinned by the simulation-cleanup gate.
%
%   cfgs = regressionConfigs()
%
% Returns a struct array with fields:
%   name        char, the reference file stem (tests/regression/data/baseline_<name>.mat)
%   about       one line saying which branch of the code this config exists to pin
%   entry       "simulate" | "simulateDiagnostic", the function under test
%   build       @() -> {state, argsCell}, so the run is reproduced exactly
%
% WHY THESE ONES. Each config exists to hold one branch that the cleanup
% (the 2026-09 simulation cleanup) is going to move, rename or
% fork. A branch with no config here is a branch the gate cannot protect, so
% adding a config is part of touching a new branch -- not an afterthought.
%
% Every run is deliberately TINY (30 cells, <= 0.05 d). The gate's job is to
% detect a changed number, not to be physically interesting: a refactor that
% alters the discretisation shows up in the first few steps just as surely as
% in ninety days, and a suite nobody waits for is a suite nobody runs.
%
% Runs start from the DEVELOPED state built by seedState, not from zero. From
% zero, 0.05 d leaves the biofilm at ~1e-9 and the enclosed phases at ~1e-18 --
% the cohesion solve, the detachment law and every Monod term would then be
% exercised on numerical nothing, and the gate would be blind to exactly the
% code the cleanup moves. See seedState.m for the measurement and the profile.
% The seed is analytic, so the suite stays self-contained: no snapshot files.

here = fileparts(mfilename("fullpath"));
W = fileparts(fileparts(here));     % tests/regression -> test -> repo root
addpath(fullfile(W, "src"));
addpath(here);      % seedState, used inside the build handles below

% Influent, keyed BY NAME rather than by position. simulate() resolves a
% dictionary against the model's own component order with FallbackValue 0, so
% the same influent serves every preset here -- including the "wolf" respiration
% branch, which inserts a fifth particle (PG) and would silently misalign a
% positional 9-vector. (It does not fail silently, in fact: it throws inside the
% convectionFlux concatenation, which is how this was found.)
INFL = dictionary( ...
    ["HET",  "PHO",  "PAT",   "O2",    "IC",    "NH4",  "HPO4", "DOM"], ...
    [3.0e-4, 1.0e-3, 5.36e-3, 9.10e-3, 1.70e-3, 2.0e-5, 9.3e-6, 1.0e-3]);

% Common short-run settings. FrameNumber is small on purpose: frames are what
% the digest stores, and 6 of them already localise a divergence to ~0.008 d.
COMMON = {"InflowConcentrations", INFL, "SimulationTime", 0.05, ...
          "FrameNumber", 6, "Quiet", true};

NCELLS = 30;

    % The production diurnal cycle (the manuscript runs', verbatim) and the same cycle
    % phase-shifted by +13/48 d so that t = 0 sits at solar noon.
    %
    % WHY THE SHIFT. The unshifted cycle is EXACTLY ZERO over the whole 0.05 d
    % window -- sunrise is at t = 1.164 d (measured 2026-09-07, max light over
    % [0, 0.05] = 0). So every config here ran at night: phototroph growth never
    % fired, and with it the light attenuation path, NormalizedLight,
    % MinimumLightFactor/OptimalLightFactor and the whole PG pool. That made
    % config 8's "wolf" arm a fraud -- PG stayed identically 0 in all three
    % phases and the run reproduced the plain default step for step (11288 both).
    % Under DAY the window is lit at 0.752-0.796 throughout, PG reaches 3.6e-6
    % and wolf separates from the default (11153 vs 11267 steps).
    %
    % Known gap, recorded rather than engineered around: the wolf r6 respiration
    % is dark-gated (K_inh/(K_inh + I)), so a lit window fills PG but inhibits
    % the reaction that consumes it. A 0.05 d window cannot hold both strong
    % light and darkness -- the cycle is a day long and the light is dim either
    % side of sunset -- so r6 is exercised only in its inhibited limit.
    DAY   = @(t) 0.8*max(sin(2*pi*(t + 13/48)) + 31/50, 0)/(1 + 31/50);
    NIGHT = @(t) 0.8*max(sin(2*pi*(t - 13/48)) + 31/50, 0)/(1 + 31/50);

    function f = filt(light)
        % A nested function cannot carry an arguments block, hence nargin.
        if nargin < 1, light = DAY; end
        f = mpcssf.SandFilter(Temperature=19, LightIrradiation=light);
        f = f.addGridPoints(NCELLS);
    end

    % modelLund AS SHIPPED. Until 2026-09-05 this preset carried Zeta0 = 1e6,
    % Zeta1 = 1/100 and a sqrt(v/7.2) detachment law, none of which matched
    % Manriquez2026 tab:general-parameters or tab:rhs-parameters, so the configs
    % here had to rebuild the Model to run the published values. The preset now
    % carries them itself and the rebuild is gone -- if it ever needs to come
    % back, the preset has drifted again and that is the bug.
    function m = campaignModel(varargin)
        m = mpcssf.presets.modelLund(varargin{:});
    end

c = struct("name", {}, "about", {}, "entry", {}, "build", {});

    function add(name, about, entry, build)
        c(end+1) = struct("name", name, "about", about, "entry", entry, "build", build);
    end

% ---- 1. the fixed-timestep branch --------------------------------------------
% The only config that does NOT use adaptive stepping, so it is what pins the
% `adaptivity == "fixed"` path and the whole CFL block being skipped.
%
% dt = 3e-7 is the largest fixed step that survives the seeded state; 1e-6 goes
% unphysical on the very first step (measured). That is not a preset defect --
% the adaptive controller picks a MEDIAN dt of 1.4e-8 here, so 1e-6 is ~70x the
% step the CFL bound actually asks for. Shorter horizon to keep it quick.
add("lund_default_fixed", ...
    "modelLund as shipped, shin + neumann, FIXED dt (pins the non-adaptive path)", ...
    "simulate", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"SimulationTime", 0.002, "TimeStep", 3e-7}]});

% ---- 2-6. one solver branch each --------------------------------------------
add("shin_neumann_adaptive", ...
    "adaptive time stepping, shin + neumann (the default production path)", "simulate", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8}]});

add("shin_dirichlet_adaptive", ...
    "the Dirichlet cohesion BC, i.e. the CH0 corner term and the uBed ghost", "simulate", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "CohesionBoundaryConditions", "dirichlet"}]});

add("explicit_dispersion", ...
    "ImplicitDispersion=false: the explicit dispersionFlux branch and its CFL weight w_a", ...
    "simulate", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "ImplicitDispersion", false}]});

% Shorter than the rest on purpose: with the osmosis relaxation explicit, 1/tau
% (tau = 1e-7) enters the CFL bound directly and pins dt around 1e-8, so 0.05 d
% costs 79 s against ~1.5 s for every other config. 0.002 d exercises the same
% branch in ~3 s, and this gate is about branch coverage, not run length.
add("explicit_osmosis", ...
    "ImplicitOsmosis=false: rhsEnclosedWater unrelaxed, on both solver sides", "simulate", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"SimulationTime", 0.002, ...
         "TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "ImplicitOsmosis", false}]});

add("film_transfer", ...
    "TransferForm=film: the grain-coating exchange rate and its exact relaxation", ...
    "simulate", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "TransferForm", "film"}]});

add("convex_splitting", ...
    "ConvexSplitting=true: the Psi'' shift into block (2,1) and its rhs counterpart", ...
    "simulate", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "ConvexSplitting", true}]});

% ---- 7. the pathogen preset -------------------------------------------------
% Covers PAT, SandAttachmentFactor (the bare-sand attachment split) and
% EfficiencyFlowing (the flowing-inert Lund reactions) in one run.
add("pathogen_sandfactor", ...
    "pathogenModel: PAT, SandAttachmentFactor, per-reaction EfficiencyFlowing", ...
    "simulate", ...
    @() {seedState(filt(), mpcssf.presets.pathogenModel(Zeta0=1, DetachForm="linear", ...
             SandPathogen=0.06, NormalizedLight=true)), ...
         [COMMON, {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8}]});

% ---- 8. every respiration branch of modelLund --------------------------------
% Step 4 collapses the PGExcess/RespirationForm double knob, so all three
% branches must be pinned before it is touched.
for form = ["reichert", "wolf", "pgexcess"]
    add("respiration_" + form, ...
        "modelLund RespirationForm=" + form + " (Step 4 collapses PGExcess into this)", ...
        "simulate", ...
        @() {seedState(filt(), campaignModel(PhototrophRespiration=0.55, ...
                 RespirationForm=form, NormalizedLight=true)), ...
             [COMMON, {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8}]});
end

% ---- 9. every theta set ------------------------------------------------------
for set = ["mixed", "reichert", "campos"]
    add("theta_" + set, ...
        "modelLund ThetaSet=" + set + " (the five TemperatureCorrectionFactor values)", ...
        "simulate", ...
        @() {seedState(filt(), campaignModel(ThetaSet=set)), ...
             [COMMON, {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8}]});
end

% ---- 10. the diagnostic path, pinned before Step 1 forks it ------------------
% These run through `simulate` today and through `simulateDiagnostic` after
% Step 1. The gate is what proves the fork faithful, so it must be captured
% BEFORE the fork exists -- hence entry is resolved at run time, not here.
add("diag_trackcfl", ...
    "TrackCFL: the CFL budget, the free-running Solver A state and the recon checks", ...
    "simulateDiagnostic", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "TrackCFL", true}]});

add("diag_bailo", ...
    "the Bailo (2023) cohesion scheme and its semismooth Newton solve", ...
    "simulateDiagnostic", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "CohesionScheme", "bailo"}]});

add("diag_matched", ...
    "the matched-flux cohesion scheme (Solver B's flux applied to phi_b)", ...
    "simulateDiagnostic", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "CohesionScheme", "matched"}]});

add("diag_posmob", ...
    "PositiveMobility: the max(lambda, 0) clamp on both the real and free states", ...
    "simulateDiagnostic", ...
    @() {seedState(filt(), campaignModel()), [COMMON, ...
        {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8, ...
         "TrackCFL", true, "PositiveMobility", true}]});

% ---- 11. the dark branch -----------------------------------------------------
% Every other config now runs at solar noon (see filt). This one keeps the night
% window that all 18 used before 2026-09-07, so the zero-light limb -- the
% MinimumLightFactor floor and the light-inhibition factor at I = 0 -- stays
% pinned rather than being traded away for the daylight coverage.
add("dark_window", ...
    "modelLund at zero light: the MinimumLightFactor floor and I = 0 inhibition", ...
    "simulate", ...
    @() {seedState(filt(NIGHT), campaignModel(PhototrophRespiration=0.55, ...
             RespirationForm="reichert", NormalizedLight=true)), ...
         [COMMON, {"TimeStep", "adaptive", "AdaptiveMaxTimeStep", 5e-5, "AdaptiveInitialTimeStep", 1e-8}]});

cfgs = c;
end
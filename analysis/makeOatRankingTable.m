map = dictionary( ...
    "temperature",    "T", ...
    "influent_PAT",   "\mathrm{PAT}_{\mathrm{in}}", ...
    "dispersivity",   "\alpha", ...
    "transport_P",    "b^{\mathrm{tr}}_{P}", ...
    "attach_sand",    "b^{\mathrm{att}}_{\mathrm{sand}}", ...
    "sand_pathogen",  "b^{\mathrm{att,PAT}}_{\mathrm{sand}}", ...
    "mu_HET",         "\mu_{\mathrm{HET}}", ...
    "mu_PHO",         "\mu_{\mathrm{PHO}}", ...
    "d_HET",          "d_{\mathrm{HET}}", ...
    "d_PHO",          "d_{\mathrm{PHO}}", ...
    "hydrolysis",     "k_{\mathrm{hyd}}", ...
    "theta_growth",   "\theta_{20,\mu}", ...
    "theta_death",    "\theta_{20,d}", ...
    "K_O2_HET",       "K^{\mathrm{O_2}}_{\mathrm{HET}}", ...
    "K_DOM_HET",      "K^{\mathrm{DOM}}_{\mathrm{HET}}", ...
    "K_HPO4_HET",     "K^{\mathrm{HPO_4}}_{\mathrm{HET}}", ...
    "K_O2_PAT",       "K^{\mathrm{O_2}}_{\mathrm{PAT}}", ...
    "K_pred",         "K_{\mathrm{pred}}", ...
    "marker_growth",  "\mu_{\mathrm{PAT}}", ...
    "inactivation",   "d_{\mathrm{PAT}}", ...
    "bacterivory",    "p_{\mathrm{PAT}}", ...
    "zeta_0",         "\zeta_0", ...
    "kappa",          "\kappa", ...
    "zeta_1",         "\zeta_1", ...
    "detach_scale",   "k_{\mathrm{det}}", ...
    "light_att_water","\eta_{\mathrm{water}}", ...
    "light_att_sand", "\eta_{\mathrm{sand}}", ...
    "attenuation_P",  "\eta_{P}", ...
    "beta_porosity",  "\beta");
if isKey(map, name), s = map(name); else, s = "\mathrm{" + name + "}"; end
end

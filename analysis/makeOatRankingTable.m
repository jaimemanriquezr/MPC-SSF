function makeOatRankingTable(resultsDir, opts)
% MAKEOATRANKINGTABLE  Booktabs body for [TAB:oat-ranking] in sensitivity.tex.
%
% Reads the same measures.csv layout as plotOatTornado (single campaign dir, or
% per-parameter log_oat_* dirs) and writes a TeX fragment with one row per
% parameter, sorted by the primary ranking I_rms. The fragment is meant to be
% \input between \toprule-ed headers the manuscript defines; it carries rows
% only, so the surrounding table stays hand-written.
%
%   makeOatRankingTable("analysis/results/oat")
arguments
    resultsDir (1,1) string = "analysis/results/oat"
    opts.OutFile (1,1) string = "analysis/results/figures/oat/oat_ranking_rows.tex"
    opts.TopN (1,1) double = Inf   % Inf = all parameters
end
T = readOatMeasures(resultsDir);
T = sortrows(T, "I_rms", "descend");
n = min(opts.TopN, height(T));

outDir = fileparts(opts.OutFile);
if ~isfolder(outDir), mkdir(outDir); end
fid = fopen(opts.OutFile, "w");
cleaner = onCleanup(@() fclose(fid));
fprintf(fid, "%% AUTOGENERATED by makeOatRankingTable from %s on %s\n", ...
    resultsDir, string(datetime("now", Format="yyyy-MM-dd")));
fprintf(fid, "%% columns: parameter & block & I_rms & I_max & D_min & asymmetry\n");
for i = 1:n
    flag = "";
    if T.clog_driver(i) ~= 0, flag = "\\textsuperscript{c}"; end
    fprintf(fid, "$%s$%s & %s & %s & %s & %s & %.2f \\\\\n", ...
        texLabel(T.param(i)), flag, T.block(i), ...
        sig2(T.I_rms(i)), sig2(T.I_max(i)), sig2(T.D_min(i)), T.asymmetry(i));
end
% the closing rule lives INSIDE this file: a \hline directly after
% \input{<this file>} inside tabular breaks on the file-end tokens
% (Misplaced \noalign), so the consumer must \input and then \end{tabular}.
fprintf(fid, "\\hline\n");
fprintf("wrote %s (%d rows)\n", opts.OutFile, n);
end

function T = readOatMeasures(resultsDir)
% same layout rules as plotOatTornado's reader
single = fullfile(resultsDir, "measures.csv");
if isfile(single)
    T = readtable(single, TextType="string");
else
    d = dir(fullfile(resultsDir, "log_oat_*", "measures.csv"));
    assert(~isempty(d), "makeOatRankingTable:noMeasures", "no measures.csv under %s", resultsDir);
    parts = cell(numel(d), 1);
    for i = 1:numel(d)
        parts{i} = readtable(fullfile(d(i).folder, d(i).name), TextType="string");
    end
    T = vertcat(parts{:});
    [~, keep] = unique(T.param, "stable");
    T = T(keep, :);
end
T.block = string(T.block); T.param = string(T.param);
end

function s = sig2(x)
% two-significant-figure scientific TeX via siunitx \num
s = sprintf("\\num{%.2g}", x);
end

